// Generates THIRD_PARTY_NOTICES.md at the repo root: every open-source package that ships inside
// RallyFlow, with its version, licence and full licence text. Fully offline (reads node_modules).
//
// What ships:
//   - the runtime dependencies in package.json "dependencies" (better-sqlite3, exceljs) and their full
//     transitive closure, because electron-builder copies those node_modules into the app;
//   - packages bundled into the renderer/main JavaScript by electron-vite (react, react-dom and their
//     dependencies);
//   - Electron itself (its own npm dependencies are download helpers and are not shipped; Chromium's
//     licences ship inside the Electron framework as LICENSES.chromium.html).
// Usage: node scripts/third-party-notices.mjs   (also run by npm run dist:mac and the release workflow)
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const rootPkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));

/** Packages bundled into out/ by electron-vite (not in "dependencies", but they ship). */
const BUNDLED = ['react', 'react-dom'];
/** Shipped, but its own npm dependencies are not. */
const LEAF_ONLY = new Set(['electron']);

/** Node's resolution: look for node_modules/<name> from `fromDir` upwards. */
function resolvePackageDir(name, fromDir) {
  let dir = fromDir;
  for (;;) {
    const candidate = join(dir, 'node_modules', name);
    if (existsSync(join(candidate, 'package.json'))) return candidate;
    const parent = dirname(dir);
    if (parent === dir) return null;
    dir = parent;
  }
}

const seen = new Map(); // dir -> package info
function visit(name, fromDir, optional) {
  const dir = resolvePackageDir(name, fromDir);
  if (!dir) {
    if (optional) return;
    throw new Error(`Cannot resolve ${name} from ${fromDir}. Run npm ci first.`);
  }
  if (seen.has(dir)) return;
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  seen.set(dir, { dir, pkg });
  if (LEAF_ONLY.has(pkg.name)) return;
  for (const dep of Object.keys(pkg.dependencies ?? {})) visit(dep, dir, false);
  for (const dep of Object.keys(pkg.optionalDependencies ?? {})) visit(dep, dir, true);
}

for (const dep of Object.keys(rootPkg.dependencies ?? {})) visit(dep, root, false);
for (const dep of BUNDLED) visit(dep, root, false);
visit('electron', root, false);

function licenseOf(pkg) {
  if (typeof pkg.license === 'string') return pkg.license;
  if (pkg.license && typeof pkg.license.type === 'string') return pkg.license.type;
  if (Array.isArray(pkg.licenses)) return pkg.licenses.map((l) => l.type ?? String(l)).join(' OR ');
  return 'See package';
}

const LICENSE_FILE = /^(licen[cs]e|copying|notice)(\.(md|txt|markdown|mit|bsd|apache|apache2))?$/i;
function licenseTexts(dir) {
  const files = readdirSync(dir).filter((f) => LICENSE_FILE.test(f)).sort();
  return files.map((f) => ({ file: f, text: readFileSync(join(dir, f), 'utf8').replace(/\r\n/g, '\n').trim() }));
}

const packages = [...seen.values()]
  .map(({ dir, pkg }) => ({ name: pkg.name, version: pkg.version, license: licenseOf(pkg), homepage: pkg.homepage ?? '', texts: licenseTexts(dir) }))
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version, undefined, { numeric: true }));

// The same name@version can be installed in several places; list it once.
const unique = [];
for (const p of packages) if (!unique.some((u) => u.name === p.name && u.version === p.version)) unique.push(p);

const fence = (text) => {
  let ticks = '```';
  while (text.includes(ticks)) ticks += '`';
  return `${ticks}text\n${text}\n${ticks}`;
};

const lines = [
  '# Third-Party Notices',
  '',
  'RallyFlow includes the open-source software listed below. Each component is used under its own',
  'licence, reproduced in full. RallyFlow itself is proprietary software (see LICENSE and EULA.md);',
  'these notices do not change the licence terms of the components.',
  '',
  'Electron bundles Chromium and Node.js; their licences ship inside the app in the Electron framework',
  '(`LICENSES.chromium.html`).',
  '',
  `Generated by \`scripts/third-party-notices.mjs\` — ${unique.length} packages.`,
  '',
  '## Summary',
  '',
  '| Package | Version | Licence |',
  '| --- | --- | --- |',
  ...unique.map((p) => `| ${p.name} | ${p.version} | ${p.license} |`),
  '',
  '## Licence texts',
  '',
];
for (const p of unique) {
  lines.push(`### ${p.name} ${p.version}`, '', `Licence: ${p.license}${p.homepage ? `  \nHomepage: ${p.homepage}` : ''}`, '');
  if (p.texts.length === 0) {
    lines.push(`No licence file is included in the published package; it is distributed under the ${p.license} licence as declared in its package.json.`, '');
  }
  for (const t of p.texts) lines.push(`\`${t.file}\`:`, '', fence(t.text), '');
}

writeFileSync(join(root, 'THIRD_PARTY_NOTICES.md'), lines.join('\n'));
console.log(`wrote THIRD_PARTY_NOTICES.md (${unique.length} packages)`);
